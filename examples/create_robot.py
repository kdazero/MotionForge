"""Rebuild the distributable geometric robot, using no external artwork."""

import argparse
import shutil
import tempfile
from pathlib import Path

from motionforge.ai_service import AIService
from motionforge.storage import write_json


def generate(destination):
    # Refuse to replace a supplied example or unrelated folder.
    if destination.exists():
        raise FileExistsError(f"Choose a new destination: {destination}")
    with tempfile.TemporaryDirectory(prefix="motionforge-example-") as folder:
        ai = AIService(Path(folder))
        ai.service.create_demo("robot")
        ai.service.add_preset("robot", "idle")
        ai.service.add_preset("robot", "wave")
        project, manifest, data = ai.service._load("robot")
        destination.mkdir(parents=True)
        shutil.copytree(project / "images", destination / "images")
        write_json(destination / "character.json", data)
        write_json(destination / "roles.json", manifest["roles"])
        (destination / "README.md").write_text(
            "# Geometric robot\n\nGenerated by MotionForge's `demo.py` using Pillow drawing primitives. "
            "No external artwork, font, photograph, model or Spine example assets are included.\n\n"
            "Code and generated example assets: MIT, Copyright (c) 2026 MotionForge contributors. "
            "See the repository LICENSE.\n\n"
            "Import character.json with images/; apply roles.json with map_roles to use presets. "
            "Contains editable idle and wave animations. This is a simple joint demonstration, "
            "not a claim of production-quality anatomy.\n",
            encoding="utf-8",
        )
    return destination


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path(__file__).parent / "robot")
    args = parser.parse_args()
    print(generate(args.output.resolve()))


if __name__ == "__main__":
    main()
